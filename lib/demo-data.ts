/**
 * Resets the Supabase database to the canonical demo dataset.
 */
export async function resetSupabaseDemoData(): Promise<void> {
  const supabase = createClient(SUPABASE_URL, SUPABASE_KEY);

  // 1. Clear tables in reverse dependency order
  await supabase.from('activities').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase.from('notifications').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase
    .from('onboarding_items')
    .delete()
    .neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase.from('candidates').delete().neq('id', '00000000-0000-0000-0000-000000000000');
  await supabase.from('openings').delete().neq('id', '00000000-0000-0000-0000-000000000000');

  // 2. Insert canonical datasets
  const { error: opErr } = await supabase.from('openings').insert(DEMO_OPENINGS);
  if (opErr) throw opErr;

  const { error: candErr } = await supabase.from('candidates').insert(DEMO_CANDIDATES);
  if (candErr) throw candErr;

  const { error: onbErr } = await supabase.from('onboarding_items').insert(DEMO_ONBOARDING_ITEMS);
  if (onbErr) throw onbErr;

  const { error: notifErr } = await supabase.from('notifications').insert(DEMO_NOTIFICATIONS);
  if (notifErr) throw notifErr;

  const { error: actErr } = await supabase.from('activities').insert(DEMO_ACTIVITIES);
  if (actErr) throw actErr;
}
